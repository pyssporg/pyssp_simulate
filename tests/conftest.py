"""Shared fixtures: a two-FMU ramp-to-integrator chain built at test time.

The fixture SSP connects two primitive FMUs that are generated by the
OpenModelica compiler (``omc``); no prebuilt binaries live in the
repository. ``tests/fmus/TestFMUs.mo`` defines the models and
``tests/generate_fmus.py`` (used by the ``test_fmus`` fixture below)
compiles them via ``tests/fmus/build_fmus.mos``:

* ``RampSource`` — a ramp source with the analytic solution
  ``y(t) = t``;
* ``Integrator`` — an integrator with ``der(y) = u`` and ``y(0) = 0``,
  so a unit ramp input gives the analytic solution ``y(t) = t²/2``.

``RampSource.y`` feeds ``Integrator.u`` through an SSD connection, so
every backend's connection machinery is exercised and the analytic
solutions give the integration tests an engine-independent reference.

FMU generation can be avoided in two ways: point the
``PYSSP_SIMULATE_TEST_FMU_DIR`` environment variable at a directory that
already contains ``RampSource.fmu`` and ``Integrator.fmu`` (fast reuse),
or pre-run ``python tests/generate_fmus.py``. When neither applies and
``omc`` is not installed, the tests that need the fixtures skip
themselves.

The fixture SSP is built with ``pyssp_standard`` (a dev dependency);
tests that only exercise pyssp_simulate itself do not require it.

The SSD carries a default experiment with an OSP fixed-step-algorithm
annotation that bakes in ``STEP_SIZE``. Backends with a step-size
command-line option pass their own value and ignore the annotation,
while the cosim backend (libcosim) has no such option and takes the
communication step from exactly this annotation.
"""

from __future__ import annotations

import os
import shutil
import zipfile
from pathlib import Path

import pytest
from tests.generate_fmus import FMU_NAMES, generate_fmus

# Environment variable pointing at a directory with prebuilt test FMUs.
FMU_DIR_ENV = "PYSSP_SIMULATE_TEST_FMU_DIR"

# Time window simulated by every backend.
START_TIME = 0.0
STOP_TIME = 1.0

# Communication step size requested from every backend.
STEP_SIZE = 0.001


def analytic_source(t: float) -> float:
    """RampSource output: ``y(t) = t``."""
    return t


def analytic_integrator(t: float) -> float:
    """Integrator output for a unit ramp input: ``y(t) = t²/2``."""
    return 0.5 * t * t


@pytest.fixture(scope="session")
def test_fmus(tmp_path_factory: pytest.TempPathFactory) -> list[Path]:
    """The test FMUs as ``[RampSource.fmu, Integrator.fmu]``.

    Reuses an existing pair when ``PYSSP_SIMULATE_TEST_FMU_DIR`` points
    at one; otherwise compiles them with omc into a session temporary
    directory, skipping when the compiler is not installed.
    """
    from_env = os.environ.get(FMU_DIR_ENV)
    if from_env:
        cached = [Path(from_env) / name for name in FMU_NAMES]
        if all(path.is_file() for path in cached):
            return cached

    if shutil.which("omc") is None:
        pytest.skip(
            "OpenModelica compiler (omc) not found — generate FMUs with "
            f"tests/generate_fmus.py or set {FMU_DIR_ENV}"
        )

    return generate_fmus(tmp_path_factory.mktemp("fmus"))


def _default_experiment():
    """Build the SSD default experiment for the test SSP."""
    from pyssp_standard.ssd import DefaultExperiment

    return DefaultExperiment(start_time=START_TIME, stop_time=STOP_TIME)


def _add_cosim_algorithm(ssp_path: Path) -> None:
    """Add the OSP fixed-step annotation to the packaged SSD.

    The refactored ``pyssp_standard`` model does not expose
    ``DefaultExperiment`` annotations, so the fixture injects the annotation
    into the packaged XML after the archive is written.  libcosim needs it to
    select a co-simulation algorithm.
    """
    from lxml import etree as ET
    from pyssp_standard.standard.ssp1.codec.xml_utils import NS_SSC, NS_SSD

    osp_ns = "http://opensimulationplatform.com/SSP/OSPAnnotations"

    def add_annotation(data: bytes) -> bytes:
        root = ET.fromstring(data)
        default = root.find("{http://ssp-standard.org/SSP1/SystemStructureDescription}DefaultExperiment")
        if default is None:
            return data
        annotations = default.find(ET.QName(NS_SSD, "Annotations"))
        if annotations is None:
            annotations = ET.SubElement(default, ET.QName(NS_SSD, "Annotations"))
        annotation = ET.SubElement(
            annotations,
            ET.QName(NS_SSC, "Annotation"),
            type="com.opensimulationplatform",
            nsmap={"ssc": NS_SSC, "osp": osp_ns},
        )
        algorithm = ET.SubElement(annotation, ET.QName(osp_ns, "Algorithm"))
        ET.SubElement(
            algorithm,
            ET.QName(osp_ns, "FixedStepAlgorithm"),
            baseStepSize=str(STEP_SIZE),
        )
        return ET.tostring(root, xml_declaration=True, encoding="utf-8")

    with zipfile.ZipFile(ssp_path) as archive:
        entries = [(info, archive.read(info.filename)) for info in archive.infolist()]

    temp_path = ssp_path.with_suffix(".tmp")
    with zipfile.ZipFile(temp_path, "w", zipfile.ZIP_DEFLATED) as archive:
        for info, data in entries:
            if info.filename == "SystemStructure.ssd":
                data = add_annotation(data)
            archive.writestr(info, data)
    temp_path.replace(ssp_path)


def _build_ssp(ssp_path: Path, fmu_paths: list[Path]) -> None:
    """Build a two-component SSP package around the test FMUs.

    ``RampSource.y`` is connected to ``Integrator.u``, forming a
    ramp-to-integrator chain; both FMUs are packaged under
    ``resources/``.
    """
    from pyssp_standard import SSP
    from pyssp_standard.ssd import Component, Connection, Connector, System

    with SSP(ssp_path, mode="w") as ssp:
        with ssp.system_structure() as ssd:
            source = Component()
            source.component_type = "application/x-fmu-sharedlibrary"
            source.name = "RampSource"
            source.source = "resources/RampSource.fmu"
            source.implementation = "CoSimulation"
            source.connectors = [Connector(name="y", kind="output", type_name="Real")]

            integrator = Component()
            integrator.component_type = "application/x-fmu-sharedlibrary"
            integrator.name = "Integrator"
            integrator.source = "resources/Integrator.fmu"
            integrator.implementation = "CoSimulation"
            integrator.connectors = [
                Connector(name="u", kind="input", type_name="Real"),
                Connector(name="y", kind="output", type_name="Real"),
            ]

            connection = Connection(
                start_element="RampSource",
                start_connector="y",
                end_element="Integrator",
                end_connector="u",
            )

            system = System(name="system")
            system.elements.append(source)
            system.elements.append(integrator)
            system.connections.append(connection)

            ssd.xml.system = system
            ssd.xml.name = "RampToIntegrator"
            ssd.xml.version = "1.0"
            ssd.xml.default_experiment = _default_experiment()

        for fmu_path in fmu_paths:
            ssp.add_resource(fmu_path)

    _add_cosim_algorithm(ssp_path)


@pytest.fixture(scope="session")
def ssp_archive(
    tmp_path_factory: pytest.TempPathFactory, test_fmus: list[Path]
) -> Path:
    """A packaged ``RampToIntegrator.ssp`` archive."""
    pytest.importorskip("pyssp_standard")
    ssp_path = tmp_path_factory.mktemp("ssp_archive") / "RampToIntegrator.ssp"
    _build_ssp(ssp_path, test_fmus)
    assert zipfile.is_zipfile(ssp_path)
    return ssp_path


@pytest.fixture(scope="session")
def ssp_dir(
    tmp_path_factory: pytest.TempPathFactory, test_fmus: list[Path]
) -> Path:
    """An unpacked SSP tree whose FMUs are also unpacked (directories).

    Backends must repackage the FMU directories into ``.fmu`` archives
    before simulating; having two unpacked FMUs also checks that the
    repackaging handles every component of a package.
    """
    pytest.importorskip("pyssp_standard")
    base = tmp_path_factory.mktemp("ssp_dir")
    archive_path = base / "RampToIntegrator.ssp"
    _build_ssp(archive_path, test_fmus)

    root = base / "RampToIntegrator"
    root.mkdir()
    with zipfile.ZipFile(archive_path) as archive:
        archive.extractall(root)

    # Unpack both packaged FMUs and remove the .fmu archives so only
    # the directories remain.
    for fmu_name in FMU_NAMES:
        fmu_dir = root / "resources" / Path(fmu_name).stem
        with zipfile.ZipFile(root / "resources" / fmu_name) as archive:
            archive.extractall(fmu_dir)
        (root / "resources" / fmu_name).unlink()
    archive_path.unlink()
    return root


